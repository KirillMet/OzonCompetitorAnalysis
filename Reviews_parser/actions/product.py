"""
==================================================
Открытие карточки товара Ozon
==================================================

Назначение:
    Проверяет текущую вкладку браузера.

    Если карточка товара уже открыта —
    ничего не делает.

    Если открыта другая страница —
    открывает PRODUCT_URL.

Модуль ничего не знает
о парсинге отзывов или API.

Он отвечает только за открытие нужной страницы.
"""

from config import PRODUCT_URL


# ==================================================
# OPEN PRODUCT
# ==================================================

async def open_product(page):
    """
    Открывает карточку товара.

    Parameters
    ----------
    page : playwright Page

    Returns
    -------
    None
    """

    print()

    print("Текущая вкладка:")

    print(page.url)

    #
    # Если уже на карточке товара —
    # повторно ничего не открываем.
    #
    if "ozon.ru/product" in page.url:

        print()

        print("Карточка товара уже открыта.")

    else:

        print()

        print("Открываю карточку товара...")

        await page.goto(
            PRODUCT_URL,
            wait_until="domcontentloaded",
            timeout=90000
        )

    #
    # Даём странице полностью загрузиться.
    #
    await page.wait_for_timeout(
        5000
    )

    print()

    print("Карточка готова к работе.")